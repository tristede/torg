  // 4. FONCTION T() V3
  // - Clé sans point => cherchée dans ui.* ; si absente, renvoyée telle quelle
  //   (permet t('Marocain') sur des labels littéraux non traduits).
  // - Clé avec point (deck.x.y, ui.x) => explicite ; si absente, renvoie ''
  //   pour que les fallbacks `t(...) || defaut` fonctionnent.
  window.t = function t(key, vars = {}) {
    if (!key) return "";
    const { lang, fallback, dict } = window.i18n;
    const rawKey = String(key);
    const isExplicit = rawKey.includes('.') && !dict.ui[rawKey];
    const finalKey = isExplicit ? rawKey : 'ui.' + rawKey;

    const parts = isExplicit ? finalKey.split('.') : ['ui', rawKey];
    let node = dict;

    for (const p of parts) {
      node = node?.[p];
      if (node === undefined) break;
    }

    // Récupération de la valeur : Langue actuelle > Fallback > défaut
    let str = node?.[lang] ?? node?.[fallback];

    if (typeof str !== 'string') {
      return isExplicit ? '' : rawKey;
    }

    // Interpolation {variable}
    for (const k in vars) {
      str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), vars[k]);
    }

    return str;
  };

